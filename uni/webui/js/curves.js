/* прогон кривой: send(0..1) — транспорт интенсивности; abort — AbortSignal */
window.runCurve=async function(name,pow,scale,abort,send){
 const sl=ms=>new Promise(r=>setTimeout(r,ms));
 const c=window.CURVES[name];
 if(c){for(const seg of c){const dur=seg[0]*scale*1000,t0=performance.now(),from=window._cur||0,to=seg[1]*pow/100;
   while(performance.now()-t0<dur){if(abort.aborted)return false;
     const k=(performance.now()-t0)/dur,v=from+(to-from)*k;window._cur=v;await send(v/100);await sl(350);}}
   window._cur=0;await send(0);return true;}
 const f=window.SIMPLEPAT[name];
 if(f){const dur=20*scale*1000,t0=performance.now();
   while(performance.now()-t0<dur){if(abort.aborted)return false;
     const v=f((performance.now()-t0)/dur)*pow/100;window._cur=v*100;await send(v);await sl(120);}
   window._cur=0;await send(0);return true;}
 return false;};